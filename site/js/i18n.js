  function tr(s) {
    if (!s) return null;
    var key = s.replace(/\s+/g, ' ').trim();
    if (!key) return null;
    if (Object.prototype.hasOwnProperty.call(D, key)) return D[key];
    for (var i = 0; i < PATTERNS.length; i++) {
      var m = key.match(PATTERNS[i][0]);
      if (m) return PATTERNS[i][1](m);
    }
    /* хлебные крошки вида "/ Контакты" */
    var bm = key.match(/^\/\s*(.+)$/);
    if (bm) {
      var inner = tr(bm[1]);
      if (inner !== null) return '/ ' + inner;
    }
    /* составные "A · B" из значений каталога */
    if (key.indexOf(' · ') > -1) {
      var parts = key.split(' · '), ok = true;
      var res = parts.map(function (p) {
        var t = tr(p);
        if (t === null) { ok = false; return p; }
        return t;
      });
      if (ok) return res.join(' · ');
    }
    return null;
  }

  function trText(node) {
    var v = node.nodeValue;
    var t = tr(v);
    if (t === null) return;
    var lead = v.match(/^\s*/)[0];
    var tail = v.match(/\s*$/)[0];
    node.nodeValue = lead + t + tail;
  }

  var ATTRS = ['placeholder', 'aria-label', 'title', 'alt'];
  function trEl(el) {
    if (!el.hasAttribute) return;
    for (var i = 0; i < ATTRS.length; i++) {
      var a = ATTRS[i];
      if (el.hasAttribute(a)) {
        var t = tr(el.getAttribute(a));
        if (t !== null) el.setAttribute(a, t);
      }
    }
  }

  function walk(root) {
    if (root.nodeType === 3) { trText(root); return; }
    if (root.nodeType !== 1) return;
    var tag = root.tagName;
    if (tag === 'SCRIPT' || tag === 'STYLE') return;
    trEl(root);
    var w = document.createTreeWalker(root, NodeFilter.SHOW_TEXT | NodeFilter.SHOW_ELEMENT, null);
    var n;
    while ((n = w.nextNode())) {
      if (n.nodeType === 3) {
        var p = n.parentElement;
        if (p && (p.tagName === 'SCRIPT' || p.tagName === 'STYLE')) continue;
        trText(n);
      } else {
        trEl(n);
      }
    }
  }

